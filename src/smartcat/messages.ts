/** 随机取一条（原 window.smartCat.getSmartCatMessage 逐字） */
export function getSmartCatMessage(messageType: string): string {
  const messages = SMART_CAT_MESSAGES[messageType];
  if (messages && messages.length > 0) return messages[Math.floor(Math.random() * messages.length)];
  return '';
}

/** 抚摸心情消息（原 window.smartCat.getPetMessage 逐字；moodState 未命中回落 neutral） */
export function getPetMessage(moodState: string): string {
  const messageType = PET_MOOD_KEYS[moodState] || 'PET_NEUTRAL_MESSAGES';
  const messages = SMART_CAT_PET_MESSAGES[messageType];
  if (messages && messages.length > 0) return messages[Math.floor(Math.random() * messages.length)];
  return '';
}